def day(
    offset: int,
    name: str,
    focus: str,
    goal: str,
    tasks: list[str],
    blanks: list[tuple[str, str]],
    choices: list[dict],
    method_cards: list[str],
    quotes: list[str],
) -> dict:
    return {
        "offset": offset,
        "day": name,
        "focus": focus,
        "goal": goal,
        "tasks": tasks,
        "blanks": blanks,
        "choices": choices,
        "method_cards": method_cards,
        "quotes": quotes,
    }


def mixed_section(
    title: str,
    blanks: list[tuple[str, str]],
    choices: list[dict],
    prompts: list[str],
    keypoints: list[str],
) -> dict:
    return {
        "title": title,
        "mixed": {"blanks": blanks, "choices": choices},
        "oral": {"prompts": prompts, "keypoints": keypoints},
    }


def write_source_markdown(output_path: Path, lesson: dict, days: list[dict], final_lines: list[str]) -> None:
    lines = [
        f"# {lesson['title']}",
        "",
        f"- 生成日期：{BASE_DATE.isoformat()}",
        f"- 使用对象：{lesson['audience']}",
        f"- 单次时长：{lesson['duration']}",
        "- 来源：6.20.1.m4a 与 6.20.2.m4a，按同一节课合并整理",
        "",
        "## 核心复习点",
        "",
    ]
    lines.extend(f"- {item}" for item in lesson["full_review_topics"])
    lines.extend(["", "## 复习节点", ""])
    for item in days:
        lines.extend(
            [
                f"### {item['day']}",
                "",
                f"- 复习重点：{item['focus']}",
                f"- 目标：{item['goal']}",
                "",
                "执行清单：",
            ]
        )
        lines.extend(f"- {task}" for task in item["tasks"])
        lines.extend(["", "填空题："])
        lines.extend(f"- {blank}（答案：{answer}）" for blank, answer in item["blanks"])
        lines.extend(["", "选择题："])
        for choice in item["choices"]:
            lines.append(f"- {choice['question']}（答案：{choice['answer']}）")
            lines.extend(f"  - {option}" for option in choice["options"])
        lines.extend(["", "课堂方法口述卡："])
        lines.extend(f"- {card}" for card in item["method_cards"])
        lines.extend(["", "课堂原话："])
        lines.extend(f"- {quote}" for quote in item["quotes"])
        lines.append("")
    lines.extend(["## 最后提醒", ""])
    lines.extend(f"- {item}" for item in final_lines)
    output_path.write_text("\n".join(lines), encoding="utf-8")


