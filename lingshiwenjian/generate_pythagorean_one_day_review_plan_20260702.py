def write_source_markdown(output_path: Path) -> None:
    lines = [
        f"# {LESSON['title']}",
        "",
        f"- 生成日期：{BASE_DATE.isoformat()}",
        f"- 模式：1天集中复习",
        f"- 使用对象：{LESSON['audience']}",
        f"- 单次时长：{LESSON['duration']}",
        "- 来源：用户提供的《勾股定理及其应用课堂逐字稿》《勾股定理及相关比例关系应用课堂逐字稿》",
        "",
        "## 核心复习点",
        "",
    ]
    lines.extend(f"- {item}" for item in LESSON["full_review_topics"])
    lines.extend(["", "## 第1天集中任务", ""])
    lines.extend(
        [
            f"- 复习重点：{DAY['focus']}",
            f"- 目标：{DAY['goal']}",
            "",
            "### 执行清单",
            "",
        ]
    )
    lines.extend(f"- {task}" for task in DAY["tasks"])
    lines.extend(["", "### 填空题", ""])
    lines.extend(f"{index}. {blank}（答案：{answer}）" for index, (blank, answer) in enumerate(DAY["blanks"], 1))
    lines.extend(["", "### 选择题", ""])
    for index, choice in enumerate(DAY["choices"], 1):
        lines.append(f"{index}. {choice['question']}（答案：{choice['answer']}）")
        lines.extend(f"   - {option}" for option in choice["options"])
    lines.extend(["", "### 老师追问口述卡", ""])
    lines.extend(f"- {card}" for card in DAY["method_cards"])
    lines.extend(["", "## 知识点加练", ""])
    for section in KNOWLEDGE_SECTIONS["第1天"]:
        lines.extend(["", f"### {section['title']}", ""])
        for blank, answer in section["mixed"]["blanks"]:
            lines.append(f"- {blank}（答案：{answer}）")
        for choice in section["mixed"]["choices"]:
            lines.append(f"- {choice['question']}（答案：{choice['answer']}）")
            lines.extend(f"  - {option}" for option in choice["options"])
        lines.append("")
        lines.extend(f"- 口述：{prompt}" for prompt in section["oral"]["prompts"])
    lines.extend(["", "## 课堂原话回放", ""])
    lines.extend(f"- “{quote}”" for quote in LESSON["quotes"])
    lines.extend(["", "## 最后提醒", ""])
    lines.extend(f"- {item}" for item in FINAL_REMINDER_LINES)
    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


